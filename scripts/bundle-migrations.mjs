#!/usr/bin/env node
// Reads all SQL migration files listed in the Drizzle journal and writes
// src/db/migrations.ts so Metro can bundle them without babel-plugin-inline-import.
// Run automatically via `npm run db:generate`.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const drizzleDir = path.join(__dirname, '../src/db/drizzle');
const outputFile = path.join(__dirname, '../src/db/migrations.ts');

const journal = JSON.parse(
  fs.readFileSync(path.join(drizzleDir, 'meta/_journal.json'), 'utf8'),
);

const exports = journal.entries.map((entry) => {
  const sqlPath = path.join(drizzleDir, `${entry.tag}.sql`);
  const sql = fs.readFileSync(sqlPath, 'utf8');
  const key = `m${String(entry.idx).padStart(4, '0')}`;
  const escaped = sql.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
  return `export const ${key} = \`${escaped}\`;`;
});

const banner = [
  '// AUTO-GENERATED by scripts/bundle-migrations.js',
  '// Do not edit manually — run `npm run db:generate` to regenerate.',
].join('\n');

fs.writeFileSync(outputFile, `${banner}\n\n${exports.join('\n\n')}\n`);

console.log(`migrations.ts updated (${journal.entries.length} migration(s))`);
